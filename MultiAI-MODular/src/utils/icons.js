let observerActive = false;
let observer = null;
let pendingRender = false;

function applyFallbacks(container) {
    const scope = container || document;
    const remaining = scope.querySelectorAll("i[data-lucide]");
    remaining.forEach(el => {
        const iconName = el.getAttribute("data-lucide");
        if (iconName && CRITICAL_SVG_FALLBACKS[iconName]) {
            const template = document.createElement("template");
            template.innerHTML = CRITICAL_SVG_FALLBACKS[iconName].trim();
            const svg = template.content.firstChild;
            if (svg) {
                el.replaceWith(svg);
            }
        }
    });
}

/**
 * Safely renders icons within the specified container or document root.
 * Never throws an exception.
 */
export function renderIcons(root) {
    try {
        if (typeof window !== "undefined" && window.lucide && typeof window.lucide.createIcons === "function") {
            window.lucide.createIcons(root ? { root } : undefined);
        } else {
            applyFallbacks(root);
        }
    } catch (err) {
        console.warn("[IconLoader] lucide.createIcons error, applying fallbacks:", err);
        try {
            applyFallbacks(root);
        } catch (_) {}
    }
}

/**
 * Schedules a debounced render of newly added icons across the document.
 */
export function scheduleIconRender() {
    if (pendingRender) return;
    pendingRender = true;
    setTimeout(() => {
        pendingRender = false;
        renderIcons();
    }, 10);
}

/**
 * Sets up a MutationObserver to automatically render icons whenever elements
 * with `data-lucide` are added into the DOM.
 */
export function initIconObserver() {
    if (observerActive || typeof MutationObserver === "undefined") return;

    try {
        observer = new MutationObserver(mutations => {
            let hasNewIcons = false;
            for (let i = 0; i < mutations.length; i++) {
                const added = mutations[i].addedNodes;
                for (let j = 0; j < added.length; j++) {
                    const node = added[j];
                    if (node && node.nodeType === 1) { // ELEMENT_NODE
                        if ((node.matches && node.matches("i[data-lucide], [data-lucide]")) || (node.querySelector && node.querySelector("i[data-lucide], [data-lucide]"))) {
                            hasNewIcons = true;
                            break;
                        }
                    }
                }
                if (hasNewIcons) break;
            }

            if (hasNewIcons) {
                scheduleIconRender();
            }
        });

        const target = document.body || document.documentElement;
        if (target) {
            observer.observe(target, { childList: true, subtree: true });
            observerActive = true;
        }
    } catch (e) {
        console.warn("[IconLoader] Observer initialization failed:", e);
    }
}

if (typeof window !== "undefined") {
    window.renderIcons = renderIcons;
}

// Automatically render immediately on module load
if (typeof document !== "undefined") {
    if (document.readyState === "loading") {
        document.addEventListener("DOMContentLoaded", () => {
            renderIcons();
            initIconObserver();
        });
    } else {
        renderIcons();
        initIconObserver();
    }
}
